import sys
import threading
import unittest
import urllib.error
import urllib.request
from http.server import ThreadingHTTPServer
from pathlib import Path

ORACLE = Path.home() / "grim-oracle"
TOOLS = Path.home() / "turd-merger-tools"
for p in (str(ORACLE), str(TOOLS)):
    if p not in sys.path:
        sys.path.insert(0, p)

import grim_serve  # noqa: E402
import grimoire_tui as tui  # noqa: E402

PROMPT = "a tool that measures whether a tool is used"


class ContractShape(unittest.TestCase):
    def test_build_contract_honours_every_field(self):
        c = grim_serve.build_contract(PROMPT, "text", "hosted-model", "answered")
        self.assertEqual(grim_serve.validate_contract(c), [])
        self.assertEqual(set(c), set(grim_serve.CONTRACT_FIELDS))

    def test_missing_field_is_reported_not_defaulted(self):
        c = grim_serve.build_contract(PROMPT, "text", "m", "r")
        c.pop("routing_reason")
        self.assertIn("missing routing_reason", grim_serve.validate_contract(c))

    def test_non_string_field_is_reported(self):
        c = grim_serve.build_contract(PROMPT, "text", None, "r")
        self.assertIn("not a string: model_used", grim_serve.validate_contract(c))

    def test_floor_text_always_travels_with_the_answer(self):
        c = grim_serve.build_contract(PROMPT, "text", "m", "r")
        self.assertIn("not generated by a model", c["offline_text"])

    def test_client_and_engine_agree_on_the_field_list(self):
        """Two copies of the contract is fine; two *different* copies is a bug."""
        self.assertEqual(grim_serve.CONTRACT_FIELDS, tui.CONTRACT_FIELDS)


class Cascade(unittest.TestCase):
    def test_first_healthy_provider_answers(self):
        calls = []

        def ok(prompt):
            calls.append("a")
            return "answer"

        out = grim_serve.cascade_ask(PROMPT, {"a": ok, "b": lambda p: "other"})
        self.assertEqual(out["response_text"], "answer")
        self.assertEqual(calls, ["a"])
        self.assertIn("answered by a", out["routing_reason"])

    def test_a_throttled_primary_is_skipped_silently(self):
        def throttled(prompt):
            raise RuntimeError("HTTP 429 from groq (model)")

        out = grim_serve.cascade_ask(PROMPT, {"groq": throttled,
                                              "deepseek": lambda p: "second"})
        self.assertEqual(out["response_text"], "second")
        self.assertIn("fell through", out["routing_reason"])
        self.assertIn("429", out["routing_reason"])
        self.assertNotIn("offline", out["model_used"])

    def test_empty_response_counts_as_failure(self):
        out = grim_serve.cascade_ask(PROMPT, {"groq": lambda p: "   ",
                                              "gemini": lambda p: "real"})
        self.assertEqual(out["response_text"], "real")
        self.assertIn("empty response", out["routing_reason"])

    def test_all_providers_down_yields_the_floor_not_an_error(self):
        def dead(prompt):
            raise RuntimeError("HTTP 402 from groq (model)")

        out = grim_serve.cascade_ask(PROMPT, {"groq": dead, "gemini": dead})
        self.assertEqual(out["model_used"], "offline")
        self.assertEqual(out["response_text"], out["offline_text"])
        self.assertEqual(grim_serve.validate_contract(out), [])
        self.assertIn("402", out["routing_reason"])

    def test_no_provider_configured_still_returns_a_contract(self):
        out = grim_serve.cascade_ask(PROMPT, {})
        self.assertEqual(out["model_used"], "offline")
        self.assertIn("no provider configured", out["routing_reason"])


class ServerOverLoopback(unittest.TestCase):
    """One real HTTP round trip on 127.0.0.1, with providers stubbed out."""

    @classmethod
    def setUpClass(cls):
        cls._real = grim_serve.build_asks
        grim_serve.build_asks = lambda primary: {}  # never touch a provider
        cls.srv = ThreadingHTTPServer(
            ("127.0.0.1", 0), grim_serve.make_handler("offline", "", "civil"))
        cls.port = cls.srv.server_address[1]
        cls.thread = threading.Thread(target=cls.srv.serve_forever, daemon=True)
        cls.thread.start()

    @classmethod
    def tearDownClass(cls):
        cls.srv.shutdown()
        cls.srv.server_close()
        grim_serve.build_asks = cls._real

    def _post(self, path, body, headers=None):
        data = json.dumps(body).encode()
        req = urllib.request.Request(
            f"http://127.0.0.1:{self.port}{path}", data=data, method="POST",
            headers={"Content-Type": "application/json", **(headers or {})})
        with urllib.request.urlopen(req, timeout=5) as resp:
            return resp.status, json.loads(resp.read().decode())

    def test_ask_returns_the_contract_when_no_provider_can_answer(self):
        status, body = self._post("/api/ask", {"prompt": PROMPT})
        self.assertEqual(status, 200)
        self.assertEqual(grim_serve.validate_contract(body), [])
        self.assertEqual(body["model_used"], "offline")

    def test_simulate_reports_the_same_contract(self):
        """Both surfaces carry model_used/routing_reason; the panel's text form
        is its JSON, because the panel is structured, not prose."""
        status, body = self._post("/api/simulate", {"pitch": "a local panel"})
        self.assertEqual(status, 200)
        contract = body.get("contract")
        self.assertIsNotNone(contract)
        self.assertEqual(grim_serve.validate_contract(contract), [])
        self.assertTrue(contract["model_used"])
        self.assertIn("answered by", contract["routing_reason"])

    def test_health_publishes_the_cascade_and_contract(self):
        with urllib.request.urlopen(
                f"http://127.0.0.1:{self.port}/api/health", timeout=5) as resp:
            body = json.loads(resp.read().decode())
        self.assertEqual(body["contract"], list(grim_serve.CONTRACT_FIELDS))
        self.assertIsInstance(body["cascade"], list)

    def test_empty_prompt_is_rejected(self):
        with self.assertRaises(urllib.error.HTTPError) as ctx:
            self._post("/api/ask", {"prompt": "   "})
        self.assertEqual(ctx.exception.code, 422)

    def test_foreign_origin_is_refused(self):
        with self.assertRaises(urllib.error.HTTPError) as ctx:
            self._post("/api/ask", {"prompt": PROMPT},
                       {"Origin": "https://evil.example"})
        self.assertEqual(ctx.exception.code, 403)


class ClientWithoutEngine(unittest.TestCase):
    """The TUI must stay usable with nothing listening on the port."""

    def _dead_url(self):
        import socket
        s = socket.socket()
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]
        s.close()  # nothing listens here now
        return f"http://127.0.0.1:{port}/api/ask"

    def test_unreachable_engine_returns_a_full_labelled_contract(self):
        out = tui.ask_engine(PROMPT, url=self._dead_url(), timeout=0.5)
        self.assertEqual(tui.validate_contract(out), [])
        self.assertEqual(out["model_used"], "offline")
        self.assertIn("unreachable", out["routing_reason"])
        self.assertIn("not generated by a model", out["response_text"])

    def test_empty_prompt_never_reaches_the_wire(self):
        out = tui.ask_engine("   ", url=self._dead_url(), timeout=0.2)
        self.assertEqual(out["model_used"], "offline")
        self.assertIn("no prompt", out["routing_reason"])

    def test_a_half_contract_is_refused_rather_than_rendered(self):
        out = tui.validate_contract({"response_text": "looks fine"})
        self.assertTrue(any("missing" in p for p in out))


