"""The boundary between the engine and any client that draws it.

Two things are being pinned here, both of which used to be promises in prose:

  * the response shape -- prompt, response_text, model_used, routing_reason,
    offline_text -- so a client can refuse a half-answer instead of rendering
    one;
  * the floor -- when every model fails, the client still gets a labelled,
    non-generated answer and never an error screen.

No network: the cascade's providers are injected, and the server test stubs
build_asks so no key is spent proving an offline floor works.
"""
