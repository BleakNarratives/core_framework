#!/usr/bin/env python3
"""
tools/guard/root_triage.py — classify the root junk drawer. READ-ONLY.

The repository root is a home directory, so it accumulates loose files that
are not in git and not in any project: dated reports, handoffs, backups,
transcripts, media, one-off scripts. This tool walks the root (depth 1) and
writes a keep/archive manifest so a human can review it later.

It NEVER moves, deletes, stages, or edits anything. It only reads names,
sizes, and the git index. "Archive" here is a *recommendation*, not an action.

Usage:
    python3 tools/guard/root_triage.py                 # -> stdout
    python3 tools/guard/root_triage.py -o tools/guard/root_triage.md
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

DISPOSITIONS = ("SHIP", "LOCAL-CONFIG", "PROTECT", "ARCHIVE-CANDIDATE", "REVIEW")

# Matched as whole tokens (split on non-alphanumerics), so "mikey_bench"
# tokenizes to {mikey, bench} and does not match "key". Listing the varied
# spellings from this workspace keeps the report honest rather than noisy.
SECRET_TOKENS = {
    "key", "keys", "keyskeys", "keyseses", "secret", "secrets", "vault",
    "token", "tokens", "password", "passwd", "credential", "credentials",
    "apikey", "dickshits",
}
ARCHIVE_EXTS = {
    ".bak", ".save", ".tmp", ".temp", ".log", ".pid", ".zip", ".tar",
    ".gz", ".tgz", ".rar", ".7z", ".png", ".jpg", ".jpeg", ".webp",
    ".wav", ".webm", ".mp3", ".mp4", ".mhtml", ".pdf", ".csv", ".jsonl",
    ".db", ".lock", ".out", ".diff",
}
# Dated evidence / one-off reports. Useful historically, but not source.
ARCHIVE_NAME_HINTS = (
    "recovery_report", "recovery_", "snapshot", "handoff", "triage",
    "audit", "drift", "_report", "report_", "session_", "inventory",
    "bootstrap_map", "who_did_what", "_summary", "canonical_state",
    "roadmap", "next_steps", "last_session", "scratch",
)
KEEP_EXTS = {".sh", ".py", ".toml", ".yaml", ".yml", ".json"}


def tracked_root_files() -> set[str]:
    out = subprocess.run(
        ("git", "ls-files"), capture_output=True, text=True, check=True
    ).stdout
    return {ln for ln in out.splitlines() if ln and "/" not in ln}


def looks_secret(name: str) -> bool:
    tokens = set(re.split(r"[^a-z0-9]+", name.lower()))
    return bool(tokens & SECRET_TOKENS)


def classify(name: str, tracked: bool) -> tuple[str, str]:
    if tracked:
        return "SHIP", "tracked by git — leave alone"
    # Secret check runs BEFORE the dotfile rule on purpose: a secret dotfile
    # (e.g. `.git-credentials`) must be PROTECT, not dismissed as local config.
    if looks_secret(name):
        return "PROTECT", "secret-shaped name — do not move/copy/paste; verify & rotate"
    if name.startswith("."):
        return "LOCAL-CONFIG", "dotfile: shell/tool config or state"
    ext = Path(name).suffix.lower()
    low = name.lower()
    if " (1)" in low or ext in ARCHIVE_EXTS:
        kind = "duplicate/attachment" if " (1)" in low else f"generated {ext or 'file'}"
        return "ARCHIVE-CANDIDATE", f"{kind} — archive or delete after review"
    if any(h in low for h in ARCHIVE_NAME_HINTS):
        return "ARCHIVE-CANDIDATE", "dated evidence/report — archive, keep out of source"
    if ext in KEEP_EXTS:
        return "REVIEW", "script/config in the root — confirm it is live before keeping"
    return "REVIEW", "unclassified — a human decides"


def main() -> int:
    ap = argparse.ArgumentParser(description="read-only root triage manifest")
    ap.add_argument("-o", "--out", help="write markdown here (default: stdout)")
    args = ap.parse_args()

    root = Path(subprocess.run(
        ("git", "rev-parse", "--show-toplevel"),
        capture_output=True, text=True, check=True,
    ).stdout.strip())
    tracked = tracked_root_files()

    rows: dict[str, list[tuple[str, str, int]]] = {d: [] for d in DISPOSITIONS}
    for p in sorted(root.iterdir(), key=lambda x: x.name.lower()):
        if not p.is_file():
            continue
        disp, reason = classify(p.name, p.name in tracked)
        rows[disp].append((p.name, reason, p.stat().st_size))

    lines: list[str] = []
    lines.append("# Root triage manifest (generated)\n")
    lines.append(
        f"**Scope:** loose files directly under the repository root "
        f"(`maxdepth 1`).  \n**Generated by:** `tools/guard/root_triage.py` "
        f"(read-only — it moves nothing).  \n**Total files:** "
        f"{sum(len(v) for v in rows.values())}\n"
    )
    lines.append("> Dispositions are **recommendations for review**, not actions.")
    lines.append("> `PROTECT` items must never be copied, pasted, or committed.\n")
    lines.append("| Disposition | Count | Meaning |")
    lines.append("|---|---:|---|")
    meaning = {
        "SHIP": "tracked in git — canonical",
        "LOCAL-CONFIG": "dotfiles / local state — leave in place",
        "PROTECT": "secret-shaped — handle separately, never commit",
        "ARCHIVE-CANDIDATE": "generated, duplicate, or dated evidence",
        "REVIEW": "needs a human decision",
    }
    for d in DISPOSITIONS:
        lines.append(f"| {d} | {len(rows[d])} | {meaning[d]} |")

    for d in DISPOSITIONS:
        if not rows[d]:
            continue
        lines.append(f"\n## {d} ({len(rows[d])})\n")
        for name, reason, size in rows[d]:
            lines.append(f"- `{name}` — {reason} ({size:,} B)")

    text = "\n".join(lines) + "\n"
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}: "
              + ", ".join(f"{d}={len(rows[d])}" for d in DISPOSITIONS))
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
